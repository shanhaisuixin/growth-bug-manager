"""
从公开语料里挑出「可以配心情」的诗词句子，生成 web/js/poem-data.js。

数据来源：chinese-poetry（MIT License，https://github.com/chinese-poetry/chinese-poetry）
        只有诗词原文取自它；下面的标签体系、打分规则、筛选逻辑全部是本项目自己写的。
        唐宋诗词本身属于公有领域。

做法（五层）：
  1. 转简   —— 语料原文是繁体（chinese-poetry 全都是），先按 OpenCC 的 TSCharacters
               表逐字转成简体。必须在「打标」之前转，因为下面那张词表写的是简体，
               拿简体词去撞繁体句是撞不上的。
  2. 切句   —— 先按 。！？ 切成一句；一联超过 14 个字再按逗号重新配对（源数据里
               五言绝句常常前两句用逗号收尾，不处理会黏成 20 个字的巨句）。
  3. 打标   —— 拿一张写好的「词 → 标签」对照表去撞这句话，撞到就记一分（词越长分越高）
  4. 点名   —— 另有一份「名句点名表」：只写片段（如「随风潜入夜」），整句从语料里
               取，并直接用点名表给的标签。这样名句既进得来，也能贴合用户写的内容。
  5. 筛选   —— 有标签的才留；**句子里每个字都得在《通用规范汉字表》一二级字表里**
               （挡掉「簷 / 罥 / 髑 / 倂」这类一眼就怪的字）；去重；控制每个标签
               的数量上限，保证分布均匀；名句选本（唐诗三百首 / 千家诗 / 水墨唐诗）
               留配额，保证库里始终有一批人人眼熟的句子。

   为什么要靠字表而不是靠词频：词频挡不住异体字。比如「簷」在语料里出现 532 次，
   比它的规范写法「檐」（587 次）只少一点，按频率排根本不掉队。而规范字表里
   有「檐」没有「簷」——这就是权威判据和统计判据的区别。

用法：
  python tools/build_poems.py <语料目录> <输出文件> [--sample] [--report]
"""

