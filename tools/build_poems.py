def load_t2s(path):
    """OpenCC 繁→简表。格式：繁<TAB>简1 简2 …；取第一个候选。"""
    m = {}
    if not os.path.exists(path):
        print('!! 找不到繁简表：%s —— 会跳过繁→简这一步' % path)
        return m
    with io.open(path, encoding='utf-8') as f:
        for ln in f:
            ln = ln.rstrip('\n')
            if not ln or ln[0] == '#':
                continue
            p = ln.split('\t')
            if len(p) < 2 or not p[1]:
                continue
            m[p[0]] = p[1].split(' ')[0]
    return m


def load_charset(dirp, names):
    """字表白名单。文件是「一行一个字」。"""
    s = set()
    for n in names:
        p = os.path.join(dirp, n)
        if not os.path.exists(p):
            print('!! 找不到字表：%s' % p)
            continue
        with io.open(p, encoding='utf-8') as f:
            s |= set(f.read().split())
    return s


