def strip_notes(s):
    """剥掉语料里的校勘注。

    这些语料带着编辑加的小注，例如曹操「龟虽寿」是这么存的：
        [..., "（螣 一作：螣）", "老骥伏枥，志在千里。", ...]
    拼成一整篇之后，注就和下一句黏在一起变成「（螣）老骥伏枥，志在千里。」，
    再被 looks_like_verse 的「不许带括号」那条整句毙掉 —— 名句就这么没了。
    所以在切句之前先把注剥干净。

    分几种写法都处理：全角括号、半角括号、以及注被拆到下一段导致括号没闭合。
    顺手也清掉语料里的两种记号：方括号标的是「编辑补的字」（如「应[制]」），
    留着会被「不许带括号」那条毙掉；□ 标的是认不出的字，显示出来是个方框。
    """
    s = re.sub(r'[（(][^（）()]*[）)]', '', s)
    s = re.sub(r'[（(][^（）()]*$', '', s)
    s = s.replace('[', '').replace(']', '').replace('□', '')
    s = s.replace('{', '').replace('}', '')
    return s


def cut(text):
    """切成候选句。

    以 。！？ 为界。麻烦在于源数据里，五言绝句经常是「前两句用逗号收尾」：
        ['床前明月光，疑是地上霜，', '举头望明月，低头思故乡。']
    直接 join 再按句号切，就会得到一条 20 个字的巨句。所以超过 MAX_COUPLET
    个字的，再按逗号拆成小截、贪心两两配回成「联」—— 这样「星垂平野阔，
    月涌大江流。」被当成一联留着，而四句黏连的会被拆成两条。
    """
    text = re.sub(r'\s+', '', text or '')
    if not text:
        return []
    out, buf = [], ''
    for ch in text:
        buf += ch
        if ch in SENT_END:
            out.append(buf)
            buf = ''
    if buf:
        out.append(buf)

    final = []
    for s in out:
        s = s.strip()
        if not s:
            continue
        if len(bare(s)) <= MAX_COUPLET:
            final.append(fix_tail(s))
            continue
        # 太长：先按逗号拆成小截
        pieces, b2 = [], ''
        for ch in s:
            b2 += ch
            if ch in '，,':
                pieces.append(b2)
                b2 = ''
        if b2:
            pieces.append(b2)
        # 再贪心配回成不超过 MAX_COUPLET 字的一联
        pack, cur, n = [], '', 0
        for p in pieces:
            pl = len(bare(p))
            if cur and n + pl > MAX_COUPLET:
                pack.append(cur)
                cur, n = '', 0
            cur += p
            n += pl
        if cur:
            pack.append(cur)
        # 拆完如果落下一条短于 MIN_LEN 的尾巴，说明这本来是一句完整的词句，
        # 硬拆只会把后半句扔掉：「此情无计可消除，才下眉头，却上心头。」会被
        # 拆成「此情无计可消除，才下眉头。」+「却上心头。」，后者四个字，必被丢。
        # 会掉字就不拆 —— 但只在整句没超过 MAX_LEN 时成立；太长的（四句黏连的
        # 五言绝句，20 个字）照样得拆。
        if any(len(bare(p)) < MIN_LEN for p in pack) and len(bare(s)) <= MAX_LEN:
            final.append(fix_tail(s))
            continue
        for p in pack:
            p = p.strip()
            if p:
                final.append(fix_tail(p))
    return final


def fix_tail(s):
    """末尾顿在逗号/分号上的，换成句号。

    语料里有三种情况都会落到这儿：
      · 拆出来的前半联：「君不见，黄河之水天上来，」
      · 曹操「老骥伏枥，志在千里；」—— 原文第二句用的是分号
      · 五言绝句前两句用逗号收尾
    一句诗末尾顿在逗号上读着像断气，也过不了 looks_like_verse。这里只换末尾
    那一个标点，正文一个字都不动。
    """
    return s[:-1] + '。' if s and s[-1] in '，,；;、' else s


def bare(s):
    return re.sub('[' + re.escape(PUNCT) + r'\s]', '', s)


def looks_like_verse(sent, b):
    """挡掉两类明显不是「一句诗」的东西：
       1. 带冒号、引号、括号（多半是序文或注）
       2. 一句很长却中间一个停顿都没有（源数据断句坏了，黏成一团）
       末尾的标点已经由 fix_tail 规范过，所以这里不再查那一项。"""
    if any(ch in sent for ch in '：:""''（）()《》「」'):
        return False
    if '，' not in sent and ',' not in sent and len(b) > 12:
        return False
    # 逗号切出来的每一截都不能太长，太长说明是黏连
    for part in re.split('[，,]', sent):
        if len(bare(part)) > 14:
            return False
    return True


def tag_line(line):
    """返回命中的标签列表（按命中强度排序）。

    只用两字以上的词。单字（「忍」「约」「守」…）太容易误伤 ——
    一个「约」字会让「依约是湘灵」变成「自律」，这种事宁可不要。
    """
    hits = defaultdict(float)
    for tag, words in LEXICON.items():
        if tag == '通用':
            continue
        for w in words:
            if len(w) < 2 or w not in line:
                continue
            hits[tag] += 1.5 if len(w) >= 4 else 1.0
    return [(t, s) for t, s in sorted(hits.items(), key=lambda x: -x[1]) if s >= 1.0]


def imagery_bonus(line):
    n = sum(1 for c in line if c in IMAGERY)
    return min(n * 0.25, 1.5)


def iter_records(path, book):
    """不同文件的结构不完全一样，这里都兼容一下。"""
    try:
        with io.open(path, encoding='utf-8') as f:
            data = json.load(f)
    except Exception:
        return
    if not isinstance(data, list):
        return
    for it in data:
        if not isinstance(it, dict):
            continue
        lines = it.get('paragraphs') or it.get('content') or it.get('para') or []
        if isinstance(lines, str):
            lines = [lines]
        text = ''.join([x for x in lines if isinstance(x, str)])
        if not text:
            continue

        # 标题：全宋词很多条目只有词牌，就用词牌当篇名
        title = it.get('title') or it.get('rhythmic') or ''
        if not str(title).strip():
            title = text[:8]

        # 作者：诗经没有作者，用「国风/小雅」这些；曹操诗集统一署曹操
        author = it.get('author') or ''
        if not str(author).strip():
            if book == '曹操诗集':
                author = '曹操'
            else:
                author = it.get('chapter') or it.get('section') or '佚名'

        yield {
            'title': str(title).strip(),
            'author': str(author).strip(),
            'text': text,
            'book': book,
        }


def _walk_poems(node, out):
    """选本文件的结构一层套一层（书 → 体裁 → 篇 → 其一/其二），
       这里递归把「有 paragraphs 的那个节点」当成一篇收下来。"""
    if isinstance(node, dict):
        ps = node.get('paragraphs')
        if isinstance(ps, list):
            texts = []
            for x in ps:
                if isinstance(x, str):
                    texts.append(x)
                else:
                    _walk_poems(x, out)     # 其二/其三 之类嵌在里面的
            if texts:
                out.append({
                    'title': node.get('chapter') or node.get('title') or '',
                    'author': node.get('author') or '',
                    'text': ''.join(texts),
                })
        else:
            for v in node.values():
                _walk_poems(v, out)
    elif isinstance(node, list):
        for v in node:
            _walk_poems(v, out)


def iter_anthology(path, book):
    """选本来的一篇一篇。author 上常挂着「（唐）」这种朝代前缀，去掉。"""
    try:
        with io.open(path, encoding='utf-8') as f:
            data = json.load(f)
    except Exception:
        return
    poems = []
    _walk_poems(data, poems)
    for p in poems:
        author = re.sub(r'^[（(][^）)]*[）)]\s*', '', p['author']).strip()
        yield {
            'title': (p['title'] or '').strip() or (p['text'][:8]),
            'author': author or '佚名',
            'text': p['text'],
            'book': book,
        }


def main():
    argv = [a for a in sys.argv[1:] if not a.startswith('--')]
    src_dir, out_file = argv[0], argv[1]

    FILES = []
    def add(name, dyn, book):
        p = os.path.join(src_dir, name)
        if os.path.exists(p) and os.path.getsize(p) > 200:
            FILES.append((p, dyn, book, 'rec'))

    def add_anth(name, dyn, book):
        p = os.path.join(src_dir, name)
        if os.path.exists(p) and os.path.getsize(p) > 200:
            FILES.append((p, dyn, book, 'anth'))

    add('shijing.json', '先秦', '诗经')
    add('chuci.json', '先秦', '楚辞')
    add('caocao.json', '汉', '曹操诗集')
    add('nalan.json', '清', '纳兰词')
    add('nantang.json', '五代', '南唐二主词')
    for f in sorted(os.listdir(src_dir)):
        if f.startswith('huajianji_'):
            add(f, '五代', '花间集')
    # —— 名句选本 ——
    add_anth('anthology_tangshisanbaishou.json', '唐', '唐诗三百首')
    add_anth('anthology_qianjiashi.json', '唐宋', '千家诗')
    add_anth('anthology_shuimotangshi.json', '唐', '水墨唐诗')
    # —— 大库（全宋词 / 全唐诗）放最后，配额由前面的选本先占 ——
    for f in sorted(os.listdir(src_dir)):
        if f.startswith('songci_'):
            add(f, '宋', '全宋词')
    for f in sorted(os.listdir(src_dir)):
        if f.startswith('tang_'):
            add(f, '唐', '全唐诗')

    print('语料文件：%d 个（含选本 %d 个）'
          % (len(FILES), sum(1 for x in FILES if x[3] == 'anth')))
    print('繁简表：%d 条；字表：%d 字' % (len(T2S), len(WHITELIST)))

    seen = {}
    total_lines = 0
    drop_rare = 0
    rare_counter = defaultdict(int)
    frag_hit = set()
    n_var_poems = 0
    n_corr_poems = 0
    # 点名表按「去标点后的正文」匹配，所以先算一遍，别在 50 万句的循环里反复算
    famous_bare = [(bare(f), f, ts) for f, ts in FAMOUS_LINES]
    for path, dyn, book, mode in FILES:
        is_anthology = ANTHOLOGY_BOOKS.get(book, 0) >= 2
        recs = iter_anthology(path, book) if mode == 'anth' else iter_records(path, book)
        for rec in recs:
            # 1) 先转简体 + 剥掉校勘注 + 异体字归一 —— 都必须在打标之前。
            #    作者和篇名也一起转，不然会出现「千山鸟飞绝 —— 柳宗元」下面
            #    署名还是繁体的怪场面。
            simple = strip_notes(to_simple(rec['text']))
            var = apply_variants(simple)
            if var != simple:
                n_var_poems += 1
            corr = apply_corrections(var)
            if corr != var:
                n_corr_poems += 1
            simple = corr
            author = to_simple(rec['author']) or '佚名'
            title = to_simple(rec['title']) or '（无题）'
            for sent in cut(simple):
                total_lines += 1
                b = bare(sent)
                if not (MIN_LEN <= len(b) <= MAX_LEN):
                    continue
                if not looks_like_verse(sent, b):
                    continue
                # 2) 字表闸门：句子正文里不许出现表外的字
                if not chars_ok(b):
                    drop_rare += 1
                    for c in rejected_chars(b):
                        rare_counter[c] += 1
                    continue
                hits = tag_line(sent)
                # 3) 点名表：撞上就是名句，标签直接用点名表给的（比词表挑的准）
                #    比的是去标点后的正文。语料的标点跟我们点名表写的往往不一样
                #    （「这次第，怎一个、愁字了得。」vs「这次第，怎一个愁字了得」），
                #    拿带标点的字符串去比会永远撞不上，名句就被「没有标签」那条
                #    规则悄悄毙掉了 —— 这个坑踩过一回，别再退回去。
                ftags = []
                for fbare, ftxt, fts in famous_bare:
                    if fbare in b:
                        frag_hit.add(fbare)
                        for t in fts:
                            if t not in ftags:
                                ftags.append(t)
                        if fbare == b and ftxt != sent:
                            # 整句就是这条名句：标点也照点名表（通行本）的写法走
                            sent = ftxt if ftxt[-1] in SENT_END else ftxt + '。'
                            b = bare(sent)
                if not hits and not ftags:
                    # 名句选本里的话，本身就是别人替你筛过一遍的 —— 「白日依山尽」
                    # 撞不上任何标签，但它显然是句人人眼熟、放哪都不违和的诗。
                    # 所以选本里的句子免掉「必须有标签」这条，归到兜底池。
                    if not is_anthology:
                        continue
                    hits = [('通用', 0.5)]
                key = b
                if key in seen:
                    continue
                fam = 3 if ftags else (ANTHOLOGY_BOOKS.get(book, 0)
                                       or GOOD_BOOKS.get(book, 0))
                score = sum(s for _, s in hits) + imagery_bonus(sent) \
                    + FAMOUS_AUTHORS.get(author, 0) * 0.6
                if book in FAMOUS_BOOKS:
                    score += 0.8
                score += fam * 1.2
                tags = []
                for t in ftags + [t for t, _ in hits]:
                    if t not in tags:
                        tags.append(t)
                tags = tags[:3]
                # 选本里的话顺带进兜底池
                if is_anthology and '通用' not in tags:
                    tags.append('通用')
                seen[key] = {
                    'text': sent,
                    'dyn': dyn,
                    'author': author,
                    'title': title,
                    'tags': tags,
                    'score': score,
                    'famous': fam,
                    'book': book,
                }

    print('扫过句子：%d，字表挡掉：%d，有标签且不重复：%d'
          % (total_lines, drop_rare, len(seen)))
    print('异体字归一：%d 篇；通行本校正：%d 篇' % (n_var_poems, n_corr_poems))
    miss_frag = [f for f, _ in FAMOUS_LINES if bare(f) not in frag_hit]
    print('点名名句：%d / %d 条在语料里撞上了'
          % (len(frag_hit), len(FAMOUS_LINES)))
    if miss_frag:
        print('   撞不上的（语料里没有，已自动跳过）：%s' % '、'.join(miss_frag))
    if '--report' in sys.argv:
        print('\n—— 被字表挡掉最多的字 top50 ——')
        print(''.join(c for c, _ in sorted(rare_counter.items(),
                                           key=lambda x: -x[1])[:50]))

    items = sorted(seen.values(), key=lambda x: -x['score'])

    # 近似去重：同一作者、同样长度、只差一个字 —— 那是同一句诗在两种版本里的
    # 异文（「莫使金樽空对月」/「莫使金尊空对月」）。全唐诗和选本各存了一份，
    # 不去重的话用户点「换一句」会看到一句几乎一样的，像卡住了。
    # 按分数从高到低扫，先到先留，所以留下的是分高的那个版本。
    by_shape = defaultdict(list)
    dup_dropped = 0
    uniq = []
    for it in items:
        key = (it['author'], len(bare(it['text'])))
        t = it['text']
        clash = False
        for prev in by_shape[key]:
            if sum(1 for a, b2 in zip(prev, t) if a != b2) <= 1:
                clash = True
                break
        if clash:
            dup_dropped += 1
            continue
        by_shape[key].append(t)
        uniq.append(it)
    items = uniq
    print('异文去重：去掉 %d 句，剩 %d 句' % (dup_dropped, len(items)))

    # 每个标签设上限，再按分数取，避免某几个标签刷屏
    per = defaultdict(int)
    kept = []
    kept_keys = set()

    def take(it):
        kept.append(it)
        kept_keys.add(it['text'])
        for t in it['tags']:
            per[t] += 1

    # —— 点名名句先全收 ——
    named = [it for it in items if it['famous'] >= 3]
    for it in named:
        take(it)
    print('点名名句保底：%d 句' % len(named))

    # —— 名句选本再占配额 ——
    # 同一首里最多留 PER_POEM_CAP 句：不然《长恨歌》《琵琶行》这种长篇会把
    # 一大截名额吃掉，名录看着就只剩两首诗了。
    anth = [it for it in items if it['famous'] == 2]
    per_poem = defaultdict(int)
    n_anth = 0
    for it in anth:
        if len(kept) >= ANTHOLOGY_QUOTA:
            break
        if per_poem[it['title']] >= PER_POEM_CAP:
            continue
        per_poem[it['title']] += 1
        take(it)
        n_anth += 1
    print('名句选本保底：%d 句（候选 %d，覆盖 %d 篇）'
          % (n_anth, len(anth), len(per_poem)))

    for it in items:
        if len(kept) >= TARGET:
            break
        if it['text'] in kept_keys:
            continue
        if all(per[t] >= PER_TAG_CAP for t in it['tags'] if t != '通用'):
            continue
        take(it)

    # 「通用」：兜底池。优先挑名句 —— 信号弱的时候，给一句眼熟的最稳。
    general = []
    pool = [it for it in items if it['text'] not in kept_keys]
    pool.sort(key=lambda x: (-x['famous'], -x['score']))
    for it in pool:
        if len(general) >= 90:
            break
        if it['tags'] and len(it['tags']) == 1 and len(bare(it['text'])) <= 14:
            general.append(it)
    for it in general:
        if '通用' not in it['tags']:
            it['tags'].append('通用')
        if it['text'] not in kept_keys:
            take(it)

    print('入选句子：%d（点名名句 %d + 选本 %d）'
          % (len(kept),
             sum(1 for it in kept if it['famous'] >= 3),
             sum(1 for it in kept if it['famous'] == 2)))
    dist = defaultdict(int)
    for it in kept:
        for t in it['tags']:
            dist[t] += 1
    for t in TAGS:
        print('   %-8s %d' % (t, dist.get(t, 0)))

    if '--sample' in sys.argv:
        print('\n—— 每个标签抽 2 句看看 ——')
        by = defaultdict(list)
        for it in kept:
            for t in it['tags']:
                by[t].append(it['text'])
        for t in TAGS:
            if t == '通用':
                continue
            for x in by[t][:2]:
                print('  %-8s %s' % (t, x))
        print('\n—— 名句抽 20 句 ——')
        n = 0
        for it in kept:
            if it['famous'] >= 2:
                print('  [f=%d %s] %s %s' % (it['famous'], it['book'],
                                             it['text'], it['author']))
                n += 1
                if n >= 20:
                    break

    tag_index = {t: i for i, t in enumerate(TAGS)}
    lines = []
    for it in kept:
        lines.append({
            't': it['text'],
            'd': it['dyn'],
            'a': it['author'],
            's': it['title'],
            'g': [tag_index[t] for t in it['tags'] if t in tag_index],
            'f': it['famous'],
        })

    payload = {
        'v': 2,
        'src': 'chinese-poetry (MIT) · 唐宋诗词原文属公有领域',
        'tags': TAGS,
        'lines': lines,
    }

    js = ('/* 诗词句库 —— 由 tools/build_poems.py 生成，不要手改这个文件。\n'
          '   原文出处：chinese-poetry（MIT）。标签体系与筛选规则是本项目自己的。\n'
          '   已繁转简、异体字归一，再按《通用规范汉字表》一二级字表挡掉生僻字；\n'
          '   名句另按一张点名表校过通行本用字。生成过程全在 tools/build_poems.py。\n'
          '   共 %d 句，其中名句选本 %d 句。 */\n'
          % (len(lines), sum(1 for it in kept if it['famous'] >= 2)) +
          'window.POEM_DATA = ' + json.dumps(payload, ensure_ascii=False,
                                             separators=(',', ':')) + ';\n')
    with io.open(out_file, 'w', encoding='utf-8', newline='\n') as f:
        f.write(js)
    print('写出：%s  %.1f KB' % (out_file, len(js.encode('utf-8')) / 1024.0))



if __name__ == '__main__':
    main()
